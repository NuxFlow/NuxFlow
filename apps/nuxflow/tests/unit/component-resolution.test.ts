import { describe, it, expect } from 'vitest'
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// A component tag Nuxt can't resolve renders nothing in production — no error, no
// warning — so a wrong name silently removes that part of the UI. This happened twice
// unnoticed: the v2-era <UNotifications /> (toasts never showed) and <MediaFolderSidebar>
// after the component moved to components/admin/media/ (registered as
// AdminMediaFolderSidebar), which hid the media folders and detail panel for a month.
//
// Checks every PascalCase tag in app/**/*.vue against what Nuxt registers
// (.nuxt/components.d.ts, generated by `nuxt prepare`) and the file's own imports.

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const declPath = path.join(appRoot, '.nuxt/components.d.ts')

const BUILTINS = new Set([
  'Teleport', 'Transition', 'TransitionGroup', 'KeepAlive', 'Suspense', 'Component',
  'RouterLink', 'RouterView', 'NuxtPage', 'NuxtLayout', 'NuxtLink', 'ClientOnly',
  'NuxtLoadingIndicator', 'NuxtErrorBoundary', 'NuxtRouteAnnouncer',
  'Head', 'Title', 'Meta', 'Link', 'Body', 'Html', 'Style', 'Base', 'NoScript',
])

function vueFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) return vueFiles(full)
    return name.endsWith('.vue') ? [full] : []
  })
}

function localNames(script: string): Set<string> {
  const names = new Set<string>()
  for (const m of script.matchAll(/import\s+(\w+)\s+from/g)) names.add(m[1]!)
  for (const m of script.matchAll(/(?:const|let)\s+(\w+)\s*=/g)) names.add(m[1]!)
  for (const m of script.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}/g)) {
    for (const part of m[1]!.split(/,|\bas\b/)) names.add(part.trim())
  }
  return names
}

describe('component tags resolve', () => {
  it.skipIf(!existsSync(declPath))('every component used in app/ is registered by Nuxt or imported', () => {
    const decl = readFileSync(declPath, 'utf8')
    const registered = new Set([...decl.matchAll(/export const (\w+):/g)].map(m => m[1]!))
    expect(registered.size).toBeGreaterThan(100)

    const unresolved: string[] = []
    for (const file of vueFiles(path.join(appRoot, 'app'))) {
      const src = readFileSync(file, 'utf8')
      const template = (src.split('<template').slice(1).join('<template')).replace(/<!--[\s\S]*?-->/g, '')
      const script = [...src.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).join('\n')
      const local = localNames(script)
      for (const [, tag] of template.matchAll(/<([A-Z][A-Za-z0-9]+)[\s/>]/g)) {
        if (BUILTINS.has(tag!) || local.has(tag!) || registered.has(tag!) || registered.has(`Lazy${tag}`)) continue
        unresolved.push(`<${tag}> in ${path.relative(appRoot, file)}`)
      }
    }
    expect([...new Set(unresolved)]).toEqual([])
  })
})
